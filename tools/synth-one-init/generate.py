#!/usr/bin/env python3
"""Compile the source firmware's INIT capture and regenerate the Remote readouts."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile

HERE = Path(__file__).resolve().parent
PIN = json.loads((HERE / "identity.json").read_bytes())


def main():
    args = argparse.ArgumentParser(description=__doc__)
    args.add_argument("firmware", type=Path)
    args.add_argument("--check", action="store_true")
    options = args.parse_args()
    source = options.firmware.resolve()
    for name, digest in PIN["inputs"].items():
        data = (source / name).read_bytes()
        if hashlib.sha1(f"blob {len(data)}\0".encode() + data).hexdigest() != digest:
            raise ValueError(f"Source input differs from pinned revision: {name}")
    part = (source / "firmware/src/app/s1_dry_part.c").read_text()
    assert "s1_dry_frozen_controls(&controls);" in part and "s1_dry_configure(voice, &controls)" in part
    dsp = source / "firmware/src/dsp"
    with tempfile.TemporaryDirectory(prefix="synth-one-init-") as tmp:
        binary = Path(tmp) / "observe"
        subprocess.run(["cc", "-std=c11", "-O2", "-ffp-contract=off", "-DX0X_HOST",
                        "-I" + str(dsp), str(HERE / "observe.c"), str(dsp / "s1_dry_voice.c"),
                        str(dsp / "dnbx_s1_envelope.c"), "-o", str(binary)], check=True)
        sample = json.loads(subprocess.check_output([binary], text=True))
    assert len(sample["points"]) == 81
    text = "// SPDX-License-Identifier: GPL-3.0-only\n// Generated by tools/synth-one-init/generate.py.\n"
    text += "export const INIT = " + json.dumps(sample, separators=(",", ":")) + ";\n"
    target = HERE.parents[1] / "web/product-site/remote/synth-one-init-data.mjs"
    if options.check:
        if target.read_text() != text:
            raise SystemExit("Compiled INIT observations differ from the Remote data")
    else:
        target.write_text(text)
    print(f"SYNTH_ONE_INIT 13 frozen values, 81 paired envelope observations at 44.1 kHz, "
          f"voice inactive at frame {sample['voiceStopSample']}")


if __name__ == "__main__":
    main()
