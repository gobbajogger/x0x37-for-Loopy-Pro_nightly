"""Compile the pinned renderer's idle branch against the original drum engines."""
import argparse
import hashlib
import json
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

RENDERER = '9dd6f2df020340f7a82ab241ef07c6ec16195ebc'
RENDERER_INPUTS = {
    'firmware/src/app/ui.c': '2cf5beae94ee319b2fc57a3728701855f57e45d0',
    'firmware/src/app/ui_drum_voice.inc': 'a0550d502668f7b476e5d11c191627f813b88c3e',
}
PRELUDE = r'''
#include <assert.h>
#include <stdio.h>
#include <string.h>
#include "drum808.h"
#include "drum909.h"
#include "fastmath.h"
enum {T_909=0,T_808=1,DG_DECAY,DG_NTAIL};
static int engine_param_si(int kit,int voice,int param,int raw,float *value) {
    return kit==T_909?drum909_param_si(voice,param,raw,value):drum808_param_si(voice,param,raw,value);
}
static void capture(int kit,int voice,int param,float ev) {
    const x0x_param_t *d=kit?drum808_param(voice,param):drum909_param(voice,param);
    assert(d && d->max==127 && (!strcmp(d->name,"Decay")||!strcmp(d->name,"Tail")));
    assert(!(kit==T_808 && voice==D8_CP));
    struct {int a,b,c;} r={kit,voice,param};
    int role=DG_DECAY,val=(int)(ev+0.5f),i,n;
    float q=ev/(float)d->max,ox=0,oy=0,sx=1,sy=1,xy[80];
'''
END = r'''
        printf("1:%d:%d:%d %.2f %s %.9g",kit,voice,param,ev,
               uu==X0X_U_MS?"ms":uu==X0X_U_S?"s":"raw",(double)ms);
        for(i=0;i<2*n;i++)printf(" %.9g",(double)xy[i]);
        putchar('\n');
    }
}
int main(void) {
    int kit,voice,param;
    while(scanf("%d%d%d",&kit,&voice,&param)==3){
        for(int raw=0;raw<=127;raw++)capture(kit,voice,param,(float)raw);
        capture(kit,voice,param,53.25f);capture(kit,voice,param,53.75f);
    }
    return 0;
}
'''

def source_donors(product):
    screens=json.loads((product/'components.json').read_bytes())['screens']
    ids=[]
    for screen in screens:
        if '-voice-' not in screen['path']:
            continue
        svg=ET.fromstring(screen['body_svg'])
        for c in screen['controls']:
            identity=c['identity']
            if c['context']['name'] not in ('Decay','Tail') or identity=='1:1:6:2':
                continue
            donor=svg.find(f".//*[@data-source-control='{identity}']//*[@data-glyph-semantic]")
            assert donor is not None and donor.get('data-glyph-semantic')==c['context']['name'].upper()
            assert len(donor)==1 and donor[0].get('d')=='M1 0C4 7 9 12 31 12'
            ids.append(identity)
    assert len(ids)==len(set(ids))==20
    return ids

def write_durations(rows):
    curves=[]
    targets={}
    for identity,records in rows.items():
        assert len(records)==130
        unit=records[0][0]
        assert all(u==unit for u,_ in records)
        if unit=='raw':
            targets[identity]=None
        else:
            values=[v for _,v in records[:128]]
            if values not in curves:
                curves.append(values)
            targets[identity]=curves.index(values)
    body=['// SPDX-License-Identifier: GPL-3.0-only',
          '// Exact unrounded milliseconds from engine_param_si; null selects the native raw fallback.',
          '// Generated by evidence/remote-owner-pages-20261121/drum-decay/source-oracle.py.',
          'export const decayMilliseconds = [']
    body.extend('  '+json.dumps(c,separators=(',',':'))+',' for c in curves)
    body.extend(['];','export const decayCurves = '+json.dumps(targets,indent=2)+';',''])
    return '\n'.join(body)

def main():
    args=argparse.ArgumentParser(description=__doc__)
    args.add_argument('nightly',type=Path)
    args.add_argument('firmware',type=Path)
    args.add_argument('output',type=Path)
    args.add_argument('--write-durations',action='store_true')
    args=args.parse_args()
    product=args.nightly/'web/product-site/remote'
    ids=source_donors(product)
    pin=json.loads((args.nightly/'tools/drum-source/identity.json').read_bytes())
    for name,digest in {**pin['inputs'],**RENDERER_INPUTS}.items():
        data=(args.firmware/name).read_bytes()
        assert hashlib.sha1(f'blob {len(data)}\0'.encode()+data).hexdigest()==digest,name
    ui=(args.firmware/'firmware/src/app/ui.c').read_text()
    assert 'if(name_is(d,"Decay")||name_is(d,"Tail")) return DG_DECAY;' in ui
    engine=(args.firmware/'firmware/src/app/engine.c').read_text()
    for kit in ('909','808'):
        assert f'case T_{kit}: return drum{kit}_param_si(v, i, pot, val);' in engine
    source=(args.firmware/'firmware/src/app/ui_drum_voice.inc').read_text()
    assert 'if(t==T_808 && v==D8_CP){dv_cp_stage_page(band);return;}' in source
    start=source.index('    if (role == DG_DECAY || role == DG_NTAIL) {',source.index('static UI_DRAW void dv_glyph('))
    end=source.index('        float back=dg_live_back',start)
    assert 'cv_poly_aa(xy, n, live?C_LINE:idle_col);' in source[end:]
    with tempfile.TemporaryDirectory() as tmp:
        work=Path(tmp)
        subprocess.run([sys.executable,str(args.firmware/'tools/gen_drum_samples.py'),
                        str(work/'x0x_drum_samples.h')],check=True,stdout=subprocess.DEVNULL)
        dsp=args.firmware/'firmware/src/dsp'
        probe=work/'probe.c';probe.write_text(PRELUDE+source[start:end]+END)
        binary=work/'probe'
        subprocess.run(['cc','-std=c11','-O2','-DX0X_HOST','-ffp-contract=off',
                        '-ffunction-sections','-fdata-sections',f'-I{dsp}',f'-I{work}',
                        str(probe),str(dsp/'drum808.c'),str(dsp/'drum909.c'),
                        str(dsp/'x0x_param.c'),'-Wl,--gc-sections','-o',str(binary)],check=True)
        commands=''.join(' '.join(i.split(':')[1:])+'\n' for i in ids)
        out=subprocess.check_output([binary],input=commands,text=True)
    args.output.write_text(out)
    rows={identity:[] for identity in ids}
    for line in out.splitlines():
        identity,_,unit,ms,*points=line.split()
        assert len(points)==34
        rows[identity].append((unit,float(ms)))
    generated=write_durations(rows)
    path=product/'drum-decay-times.mjs'
    if args.write_durations:
        path.write_text(generated)
    else:
        assert path.read_text()==generated,'drum-decay-times.mjs does not match native units'

if __name__=='__main__':
    main()
